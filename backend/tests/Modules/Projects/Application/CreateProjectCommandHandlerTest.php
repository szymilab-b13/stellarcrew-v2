<?php

declare(strict_types=1);

namespace App\Tests\Modules\Projects\Application;

use App\Tests\Fixtures\Projects\FakeWorkspacesApi;
use App\Tests\Fixtures\Projects\InMemoryProjectRepository;
use DateTimeImmutable;
use Modules\Projects\Application\CreateProjectCommand;
use Modules\Projects\Application\CreateProjectCommandHandler;
use Modules\Shared\Kernel\FrozenClock;
use Modules\Shared\Kernel\UserId;
use Modules\Shared\Kernel\WorkspaceId;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;
use Symfony\Component\Security\Core\Exception\AccessDeniedException;
use Symfony\Component\Uid\Uuid;

final class CreateProjectCommandHandlerTest extends TestCase
{
    public function testShouldPersistProjectWithAutoGeneratedSlugWhenSlugMissing(): void
    {
        $workspaceId = WorkspaceId::generate();
        $actorId = new UserId(Uuid::v7());
        $repo = new InMemoryProjectRepository();
        $workspaces = (new FakeWorkspacesApi())
            ->withWorkspace($workspaceId)
            ->withPermission($workspaceId, $actorId, CreateProjectCommandHandler::PERMISSION);
        $sut = new CreateProjectCommandHandler(
            $repo,
            $workspaces,
            new FrozenClock(new DateTimeImmutable('2026-11-09T10:00:00+00:00')),
        );

        $project = $sut(new CreateProjectCommand($actorId, $workspaceId, 'My Project'));

        self::assertSame(1, $repo->count());
        self::assertSame('My Project', $project->name());
        self::assertSame('my-project', $project->slug());
        self::assertNull($project->description());
        self::assertTrue($project->workspaceId()->equals($workspaceId));
    }

    public function testShouldPersistProjectWithProvidedSlugAndDescription(): void
    {
        $workspaceId = WorkspaceId::generate();
        $actorId = new UserId(Uuid::v7());
        $repo = new InMemoryProjectRepository();
        $workspaces = (new FakeWorkspacesApi())
            ->withWorkspace($workspaceId)
            ->withPermission($workspaceId, $actorId, CreateProjectCommandHandler::PERMISSION);
        $sut = new CreateProjectCommandHandler(
            $repo,
            $workspaces,
            new FrozenClock(new DateTimeImmutable('2026-11-09T10:00:00+00:00')),
        );

        $project = $sut(new CreateProjectCommand(
            actorId: $actorId,
            workspaceId: $workspaceId,
            name: 'Talent Bridge',
            slug: 'tb-mvp',
            description: 'POC scope',
        ));

        self::assertSame('tb-mvp', $project->slug());
        self::assertSame('POC scope', $project->description());
    }

    public function testShouldAppendRandomSuffixWhenSlugAlreadyTakenInSameWorkspace(): void
    {
        $workspaceId = WorkspaceId::generate();
        $actorId = new UserId(Uuid::v7());
        $repo = new InMemoryProjectRepository();
        $workspaces = (new FakeWorkspacesApi())
            ->withWorkspace($workspaceId)
            ->withPermission($workspaceId, $actorId, CreateProjectCommandHandler::PERMISSION);
        $sut = new CreateProjectCommandHandler(
            $repo,
            $workspaces,
            new FrozenClock(new DateTimeImmutable('2026-11-09T10:00:00+00:00')),
        );
        $sut(new CreateProjectCommand($actorId, $workspaceId, 'Alpha'));

        $second = $sut(new CreateProjectCommand($actorId, $workspaceId, 'Alpha'));

        self::assertNotSame('alpha', $second->slug());
        self::assertStringStartsWith('alpha-', $second->slug());
    }

    public function testShouldReuseSlugAcrossDifferentWorkspaces(): void
    {
        $workspaceA = WorkspaceId::generate();
        $workspaceB = WorkspaceId::generate();
        $actorId = new UserId(Uuid::v7());
        $repo = new InMemoryProjectRepository();
        $workspaces = (new FakeWorkspacesApi())
            ->withWorkspace($workspaceA)
            ->withWorkspace($workspaceB)
            ->withPermission($workspaceA, $actorId, CreateProjectCommandHandler::PERMISSION)
            ->withPermission($workspaceB, $actorId, CreateProjectCommandHandler::PERMISSION);
        $sut = new CreateProjectCommandHandler(
            $repo,
            $workspaces,
            new FrozenClock(new DateTimeImmutable('2026-11-09T10:00:00+00:00')),
        );
        $sut(new CreateProjectCommand($actorId, $workspaceA, 'Shared'));

        $second = $sut(new CreateProjectCommand($actorId, $workspaceB, 'Shared'));

        self::assertSame('shared', $second->slug());
    }

    public function testShouldThrowNotFoundWhenWorkspaceDoesNotExist(): void
    {
        $workspaceId = WorkspaceId::generate();
        $actorId = new UserId(Uuid::v7());
        $sut = new CreateProjectCommandHandler(
            new InMemoryProjectRepository(),
            new FakeWorkspacesApi(),
            new FrozenClock(new DateTimeImmutable('2026-11-09T10:00:00+00:00')),
        );

        $this->expectException(NotFoundHttpException::class);

        $sut(new CreateProjectCommand($actorId, $workspaceId, 'My Project'));
    }

    public function testShouldThrowAccessDeniedWhenActorHasNoProjectsCreatePermission(): void
    {
        $workspaceId = WorkspaceId::generate();
        $actorId = new UserId(Uuid::v7());
        $workspaces = (new FakeWorkspacesApi())->withWorkspace($workspaceId);
        $sut = new CreateProjectCommandHandler(
            new InMemoryProjectRepository(),
            $workspaces,
            new FrozenClock(new DateTimeImmutable('2026-11-09T10:00:00+00:00')),
        );

        $this->expectException(AccessDeniedException::class);

        $sut(new CreateProjectCommand($actorId, $workspaceId, 'My Project'));
    }

    public function testShouldStampTimestampsFromClock(): void
    {
        $workspaceId = WorkspaceId::generate();
        $actorId = new UserId(Uuid::v7());
        $now = new DateTimeImmutable('2026-11-09T10:00:00+00:00');
        $workspaces = (new FakeWorkspacesApi())
            ->withWorkspace($workspaceId)
            ->withPermission($workspaceId, $actorId, CreateProjectCommandHandler::PERMISSION);
        $sut = new CreateProjectCommandHandler(
            new InMemoryProjectRepository(),
            $workspaces,
            new FrozenClock($now),
        );

        $project = $sut(new CreateProjectCommand($actorId, $workspaceId, 'Timed'));

        self::assertEquals($now, $project->createdAt());
        self::assertEquals($now, $project->updatedAt());
    }
}
