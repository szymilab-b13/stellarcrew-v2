<?php

declare(strict_types=1);

namespace App\Tests\Modules\Organizations\Application;

use App\Tests\Fixtures\Core\SpyAuditLogger;
use App\Tests\Fixtures\Organizations\InMemoryOrganizationRepository;
use DateTimeImmutable;
use Modules\Organizations\Application\CreateOrganizationCommand;
use Modules\Organizations\Application\CreateOrganizationCommandHandler;
use Modules\Organizations\Domain\OwnerAlreadyHasOrganizationException;
use Modules\Shared\Kernel\FrozenClock;
use Modules\Shared\Kernel\UserId;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Uid\Uuid;

final class CreateOrganizationCommandHandlerTest extends TestCase
{
    public function testShouldPersistOrganizationWithAutoGeneratedSlugWhenSlugMissing(): void
    {
        $ownerId = new UserId(Uuid::v7());
        $repo = new InMemoryOrganizationRepository();
        $sut = new CreateOrganizationCommandHandler(
            $repo,
            new SpyAuditLogger(),
            new FrozenClock(new DateTimeImmutable('2026-11-10T14:00:00+00:00')),
        );

        $organization = $sut(new CreateOrganizationCommand($ownerId, "Alice's Organization"));

        self::assertSame(1, $repo->count());
        self::assertSame("Alice's Organization", $organization->name());
        self::assertSame('alice-s-organization', $organization->slug());
        self::assertTrue($organization->ownerUserId()->equals($ownerId));
    }

    public function testShouldPersistOrganizationWithProvidedSlug(): void
    {
        $ownerId = new UserId(Uuid::v7());
        $repo = new InMemoryOrganizationRepository();
        $sut = new CreateOrganizationCommandHandler(
            $repo,
            new SpyAuditLogger(),
            new FrozenClock(new DateTimeImmutable('2026-11-10T14:00:00+00:00')),
        );

        $organization = $sut(new CreateOrganizationCommand(
            ownerUserId: $ownerId,
            name: 'Acme',
            slug: 'acme-inc',
        ));

        self::assertSame('acme-inc', $organization->slug());
    }

    public function testShouldAppendRandomSuffixWhenSlugAlreadyTakenByAnotherOwner(): void
    {
        $ownerA = new UserId(Uuid::v7());
        $ownerB = new UserId(Uuid::v7());
        $repo = new InMemoryOrganizationRepository();
        $sut = new CreateOrganizationCommandHandler(
            $repo,
            new SpyAuditLogger(),
            new FrozenClock(new DateTimeImmutable('2026-11-10T14:00:00+00:00')),
        );
        $sut(new CreateOrganizationCommand($ownerA, 'Acme'));

        $second = $sut(new CreateOrganizationCommand($ownerB, 'Acme'));

        self::assertNotSame('acme', $second->slug());
        self::assertStringStartsWith('acme-', $second->slug());
    }

    public function testShouldThrowWhenOwnerAlreadyHasActiveOrganization(): void
    {
        $ownerId = new UserId(Uuid::v7());
        $repo = new InMemoryOrganizationRepository();
        $sut = new CreateOrganizationCommandHandler(
            $repo,
            new SpyAuditLogger(),
            new FrozenClock(new DateTimeImmutable('2026-11-10T14:00:00+00:00')),
        );
        $sut(new CreateOrganizationCommand($ownerId, 'First'));

        $this->expectException(OwnerAlreadyHasOrganizationException::class);

        $sut(new CreateOrganizationCommand($ownerId, 'Second'));
    }

    public function testShouldStampTimestampsFromClock(): void
    {
        $ownerId = new UserId(Uuid::v7());
        $now = new DateTimeImmutable('2026-11-10T14:00:00+00:00');
        $sut = new CreateOrganizationCommandHandler(
            new InMemoryOrganizationRepository(),
            new SpyAuditLogger(),
            new FrozenClock($now),
        );

        $organization = $sut(new CreateOrganizationCommand($ownerId, 'Timed'));

        self::assertEquals($now, $organization->createdAt());
        self::assertEquals($now, $organization->updatedAt());
    }

    public function testShouldRecordAuditEntryWithOwnerAndAfterStateSnapshot(): void
    {
        $ownerId = new UserId(Uuid::v7());
        $audit = new SpyAuditLogger();
        $sut = new CreateOrganizationCommandHandler(
            new InMemoryOrganizationRepository(),
            $audit,
            new FrozenClock(new DateTimeImmutable('2026-11-10T14:00:00+00:00')),
        );

        $organization = $sut(new CreateOrganizationCommand(
            ownerUserId: $ownerId,
            name: 'Acme',
            slug: 'acme-inc',
        ));

        self::assertCount(1, $audit->entries);
        $entry = $audit->entries[0];
        self::assertSame(CreateOrganizationCommandHandler::AUDIT_ACTION, $entry->action);
        self::assertSame(CreateOrganizationCommandHandler::AUDIT_RESOURCE_TYPE, $entry->resourceType);
        self::assertSame((string) $organization->id(), $entry->resourceId);
        self::assertNotNull($entry->userId);
        self::assertTrue($entry->userId->equals($ownerId));
        self::assertArrayHasKey('after_state', $entry->metadata);
        self::assertSame((string) $organization->id(), $entry->metadata['after_state']['id']);
        self::assertSame('Acme', $entry->metadata['after_state']['name']);
        self::assertSame('acme-inc', $entry->metadata['after_state']['slug']);
        self::assertSame((string) $ownerId, $entry->metadata['after_state']['owner_user_id']);
    }
}
