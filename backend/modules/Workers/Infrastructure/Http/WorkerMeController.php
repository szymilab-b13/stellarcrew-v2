<?php

declare(strict_types=1);

namespace Modules\Workers\Infrastructure\Http;

use DateTimeInterface;
use Modules\Chat\Application\GetOrCreateThreadWorkerSessionCommand;
use Modules\Chat\Application\GetOrCreateThreadWorkerSessionCommandHandler;
use Modules\Chat\Application\RecordAgentReplyCommand;
use Modules\Chat\Application\RecordAgentReplyCommandHandler;
use Modules\Shared\Kernel\ChatMessageId;
use Modules\Shared\Kernel\ChatThreadId;
use Modules\Workers\Application\IssueTokenCommand;
use Modules\Workers\Application\IssueTokenCommandHandler;
use Modules\Workers\Infrastructure\Support\WorkerAuthenticator;
use OpenApi\Attributes as OA;
use Symfony\Component\HttpFoundation\JsonResponse;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Attribute\MapRequestPayload;
use Symfony\Component\Routing\Attribute\Route;
use Symfony\Component\Uid\Uuid;

final readonly class WorkerMeController
{
    public function __construct(
        private WorkerAuthenticator $authenticator,
        private GetOrCreateThreadWorkerSessionCommandHandler $getOrCreateSession,
        private RecordAgentReplyCommandHandler $recordAgentReply,
        private IssueTokenCommandHandler $issueToken,
    ) {
    }

    #[Route('/api/workers/me/token', name: 'workers_me_token', methods: ['POST'])]
    #[OA\Post(
        path: '/api/workers/me/token',
        summary: 'Exchange a refresh token for a short-lived JWT access token',
        tags: ['workers-me'],
        responses: [
            new OA\Response(response: 200, description: 'Access token issued, refresh rotated'),
            new OA\Response(response: 401, description: 'Refresh token invalid, expired or already used'),
        ],
    )]
    public function token(#[MapRequestPayload] IssueTokenRequest $request): JsonResponse
    {
        $result = ($this->issueToken)(new IssueTokenCommand(
            refreshToken: $request->refreshToken,
            fingerprintHash: $request->fingerprintHash,
            fingerprintMeta: $request->fingerprintMeta,
            hostInfo: $request->hostInfo,
        ));

        return new JsonResponse([
            'accessToken' => $result->accessToken,
            'refreshToken' => $result->refreshToken,
            'expiresIn' => $result->expiresIn,
            'tokenType' => 'Bearer',
            'fingerprintWarning' => $result->fingerprintWarning,
            'previousFingerprintMeta' => $result->previousFingerprintMeta,
            'currentFingerprintHash' => $result->currentFingerprintHash,
        ]);
    }

    #[Route(
        '/api/workers/me/threads/{threadId}/session',
        name: 'workers_me_get_or_create_session',
        requirements: ['threadId' => '[0-9a-fA-F-]{36}'],
        methods: ['GET'],
    )]
    #[OA\Get(
        path: '/api/workers/me/threads/{threadId}/session',
        summary: 'Fetch or create the Claude session id for a thread on this worker',
        tags: ['workers-me'],
        responses: [
            new OA\Response(response: 200, description: 'Session resolved'),
            new OA\Response(response: 403, description: 'Invalid worker credentials'),
            new OA\Response(response: 404, description: 'Thread not found'),
        ],
    )]
    public function getOrCreateSession(string $threadId, Request $request): JsonResponse
    {
        $worker = $this->authenticator->authenticate($request);
        $session = ($this->getOrCreateSession)(new GetOrCreateThreadWorkerSessionCommand(
            threadId: ChatThreadId::fromString($threadId),
            workerId: $worker->id(),
        ));

        return new JsonResponse([
            'threadId' => (string) $session->threadId(),
            'workerId' => (string) $session->workerId(),
            'claudeSessionId' => (string) $session->claudeSessionId(),
            'lastMessageAt' => $session->lastMessageAt()?->format(DateTimeInterface::ATOM),
        ]);
    }

    #[Route('/api/workers/me/messages', name: 'workers_me_record_message', methods: ['POST'])]
    #[OA\Post(
        path: '/api/workers/me/messages',
        summary: 'Record an agent reply generated by this worker',
        tags: ['workers-me'],
        responses: [
            new OA\Response(response: 201, description: 'Message persisted'),
            new OA\Response(response: 403, description: 'Invalid worker credentials'),
            new OA\Response(response: 404, description: 'Thread not found'),
        ],
    )]
    public function recordMessage(Request $request, #[MapRequestPayload] WorkerRecordMessageRequest $payload): JsonResponse
    {
        $worker = $this->authenticator->authenticate($request);
        $replyTo = $payload->replyToMessageId !== null ? ChatMessageId::fromString($payload->replyToMessageId) : null;

        $message = ($this->recordAgentReply)(new RecordAgentReplyCommand(
            threadId: ChatThreadId::fromString($payload->threadId),
            workerId: $worker->id(),
            agentId: Uuid::fromString($payload->agentId),
            content: $payload->content,
            replyToMessageId: $replyTo,
        ));

        return new JsonResponse([
            'messageId' => (string) $message->id(),
            'threadId' => (string) $message->threadId(),
            'createdAt' => $message->createdAt()->format(DateTimeInterface::ATOM),
        ], Response::HTTP_CREATED);
    }
}
